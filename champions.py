def search_champions(query, limit=8):
    """
    Filtra campeones por coincidencia en tiempo real.
    Prioriza campeones que empiezan con el término de búsqueda,
    seguidos de aquellos que lo contienen.
    """
    if not query:
        return []
    
    q = query.strip().lower()
    if not q:
        return []

    prefix_matches = []
    contains_matches = []

    for name in CHAMPIONS:
        name_lower = name.lower()
        if name_lower.startswith(q):
            prefix_matches.append(name)
        elif q in name_lower:
            contains_matches.append(name)

    results = prefix_matches + contains_matches
    return results[:limit]
